"""
Configuration for the metrics dashboard pipeline.

Every value here can be overridden by an environment variable of the same
name (upper-cased) so the same code works locally, in CI, and if the sheet
ever moves — without editing this file.
"""

import os

# Where fetch_rows() reads from. "local" (default) reads LOCAL_DATA_PATH via
# pandas — no Google libraries or credentials needed. Switch to
# "google_sheets" once real Sheets access is wired up (see README's
# "Connecting the real sheet later" section); no other code needs to change.
DATA_SOURCE = os.environ.get("DATA_SOURCE", "local")

# Stand-in dataset used while DATA_SOURCE == "local". Generated by
# pipeline/sample_data/generate_sample.py.
LOCAL_DATA_PATH = os.environ.get(
    "LOCAL_DATA_PATH",
    os.path.join(os.path.dirname(__file__), "sample_data", "tracking_sheet.csv"),
)

# The Google Sheet's ID (the long id in its URL, between /d/ and /edit).
# Only used when DATA_SOURCE == "google_sheets".
SHEET_ID = os.environ.get("SHEET_ID", "REPLACE_WITH_YOUR_SHEET_ID")

# Name of the worksheet (tab) that holds the query-tracking rows.
WORKSHEET_NAME = os.environ.get("WORKSHEET_NAME", "Sheet1")

# Exact header text of the column to bar-chart. Must match the sheet exactly.
GAP_COLUMN = os.environ.get(
    "GAP_COLUMN", "Nature of the gap they want to close"
)

# Value substituted for blank/missing entries in GAP_COLUMN so they still
# show up in the chart instead of silently vanishing from the count.
MISSING_LABEL = "Unspecified"

# Exact header text of the column used to build the "queries per month"
# trend chart. Must match the sheet exactly. Unparseable/blank timestamps
# are dropped from that chart (they can't be placed on a timeline) rather
# than substituted, unlike GAP_COLUMN's MISSING_LABEL bucket.
TIMESTAMP_COLUMN = os.environ.get("TIMESTAMP_COLUMN", "Timestamp")

# Where the pipeline writes its output. Read by docs/app.js as a relative
# path, so this must stay inside docs/.
OUTPUT_PATH = os.environ.get(
    "OUTPUT_PATH",
    os.path.join(os.path.dirname(__file__), "..", "docs", "data", "stats.json"),
)

# Read-only scope for the MVP. When write-back features are added later,
# switch this single line to the read-write scope
# ('https://www.googleapis.com/auth/spreadsheets') — no other auth code
# needs to change, and the service account is already shared as an Editor
# on the sheet (see README) so no re-sharing is needed either.
SCOPES = ["https://www.googleapis.com/auth/spreadsheets.readonly"]
